// ===== CSVをパースしてTilemapDataに変換=====
export function parseTilemapCSV(csv: string, mapWidth: number, mapHeight: number): TilemapData {
  const lines = csv.trim().split('\n').filter(line => line.trim());
  const data: number[][] = [];
  
  for (const line of lines) {
    const row = line.split(',').map(v => parseInt(v.trim(), 10));
    if (row.length === mapWidth) {
      data.push(row);
    }
  }
  
  // 高さが足りない場合は草(1)で埋める
  while (data.length < mapHeight) {
    data.push(new Array(mapWidth).fill(1));
  }
  
  return {
    width: mapWidth,
    height: mapHeight,
    tileSize: TILE_SIZE,
    layers: [
      {
        name: 'ground',
        data,
        visible: true,
        collision: false,
      },
      {
        name: 'collision',
        data: data.map(row => row.map(v => (v === 1 || v === 3 || v === 4 || v === 6) ? 1 : 0)),
        visible: false,
        collision: true,
      },
    ],
    objects: [],
  };
}

